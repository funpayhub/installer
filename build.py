# Replaces PyInstaller's own PySide6 hooks: same thing, but the unneeded plugins are dropped before PyInstaller
# looks for their dependencies, otherwise the GTK theme plugin alone drags in GTK, ICU and half of the system
HOOK = f"""# Generated by build.py
from PyInstaller.utils.hooks.qt import add_qt6_dependencies

DROP_FILES = {DROP_FILES!r}


def keep(entry):
    path = str(entry[0]).replace('\\\\', '/').lower()
    return not any(part.lower() in path for part in DROP_FILES)


hiddenimports, binaries, datas = add_qt6_dependencies(__file__)
binaries = [i for i in binaries if keep(i)]
datas = [i for i in datas if keep(i)]
"""

SPEC = f"""# Generated by build.py
from pathlib import Path

ROOT = Path({str(ROOT)!r})
DROP_FILES = {DROP_FILES!r}


def keep(entry):
    path = entry[0].replace('\\\\', '/').lower()
    return not any(part.lower() in path for part in DROP_FILES)


analysis = Analysis(
    [str(ROOT / 'dothub_installer' / '__main__.py')],
    pathex=[str(ROOT)],
    hookspath=[{str(HOOKS)!r}],
    datas=[
        (str(ROOT / 'install.sh'), '.'),
        (str(ROOT / 'install.ps1'), '.'),
        (str(ROOT / 'dothub_installer' / 'ui' / 'assets'), 'dothub_installer/ui/assets'),
    ],
    excludes={EXCLUDE_MODULES!r},
    optimize=2,  # bytecode without docstrings and asserts
)
analysis.binaries = [i for i in analysis.binaries if keep(i)]
analysis.datas = [i for i in analysis.datas if keep(i)]

exe = EXE(
    PYZ(analysis.pure),
    analysis.scripts,
    analysis.binaries,
    analysis.datas,
    [],
    name={NAME!r},
    console=False,
    icon={str(BUILD / "icon.ico")!r},
    strip={sys.platform != "win32"!r},
    upx=False,
)
"""


def main() -> None:
    BUILD.mkdir(exist_ok=True)
    app = QGuiApplication([])
    for icon in (BUILD / "icon.ico", BUILD / "icon.png"):
        if not logo_pixmap(256).save(str(icon)):
            raise SystemExit(f"Unable to write {icon}")

    HOOKS.mkdir(exist_ok=True)
    for module in ("QtCore", "QtGui", "QtWidgets", "QtSvg"):
        (HOOKS / f"hook-PySide6.{module}.py").write_text(HOOK, encoding="utf-8")

    spec = BUILD / f"{NAME}.spec"
    spec.write_text(SPEC, encoding="utf-8")
    PyInstaller.__main__.run(
        [
            str(spec),
            "--noconfirm",
            f"--distpath={ROOT / 'dist'}",
            f"--workpath={BUILD / 'work'}",
        ]
    )


if __name__ == "__main__":
    main()
